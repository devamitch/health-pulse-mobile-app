import BaseModal from '@/components/modals/base-modal';
import { ColorScheme } from '@/constants/theme';
import { useAppTheme } from '@/hooks/themeHook';
import { useAppDispatch, useAppSelector } from '@/services/mmkv-redux/hooks';
import { acceptDisclaimer } from '@/services/mmkv-redux/slices';
import { StyleSheet, Text, View } from 'react-native';
import { RectButton } from 'react-native-gesture-handler';

interface MiniDisclaimerProps {
  visible: boolean;
  onClose: () => void;
}

const MiniDisclaimer = ({ visible, onClose }: MiniDisclaimerProps) => {
  const { Colors } = useAppTheme();
  const styles = createStyles(Colors);
  const dispatch = useAppDispatch();
  const showMiniReminders = useAppSelector(
    state => state?.user?.disclaimerSettings?.showMiniReminders,
  );

  const handleDontShowAgain = async () => {
    try {
      await dispatch(
        acceptDisclaimer({
          dontShowAgain: true, // Keep the main disclaimer settings
          showMiniReminders: false, // Turn off mini reminders
        }),
      );
      onClose();
    } catch (error) {
      console.error('Failed to update disclaimer settings:', error);
    }
  };

  if (!showMiniReminders) return null;

  const disclaimerPoints = [
    'This is an AI-powered medical information assistant, not an actual healthcare provider',
    'Content is generated by artificial intelligence and should not be considered medical advice',
    'AI responses may contain errors or inaccuracies - always verify with a qualified professional',
    'Not intended for diagnosis, treatment, or prevention of any disease or health condition',
    'Does not replace the relationship between patient and physician',
    'For emergency situations, contact your local emergency services immediately',
    'Information provided may not be complete, current, or applicable to your specific situation',
    'Never disregard professional medical advice because of something you read in this app',
  ];

  return (
    <BaseModal
      isVisible={visible}
      onClose={onClose}
      showBackButton={false}
      showHeader={false}
      buttons={
        <View style={styles.buttonContainer}>
          <RectButton
            style={[styles.button, styles.secondaryButton]}
            onPress={onClose}
          >
            <Text style={[styles.buttonText, styles.secondaryButtonText]}>
              Remind me later
            </Text>
          </RectButton>
          <RectButton
            style={[styles.button, styles.primaryButton]}
            onPress={handleDontShowAgain}
          >
            <Text style={[styles.buttonText, styles.primaryButtonText]}>
              Don't show again
            </Text>
          </RectButton>
        </View>
      }
    >
      <View style={styles.container}>
        <Text style={styles.header}>Important Health Information Notice</Text>

        <View style={styles.content}>
          <Text style={styles.text}>
            This AI medical assistant provides general health information for
            educational purposes only:
          </Text>

          <View style={styles.listContainer}>
            {disclaimerPoints.map((point, index) => (
              <View key={index} style={styles.listItem}>
                <View style={styles.bulletPoint} />
                <Text style={styles.listText}>{point}</Text>
              </View>
            ))}
          </View>

          <Text style={styles.footerText}>
            By continuing to use this app, you acknowledge that you understand
            these limitations.
          </Text>
        </View>
      </View>
    </BaseModal>
  );
};

const createStyles = (Colors: ColorScheme) =>
  StyleSheet.create({
    container: {
      padding: 12,
    },
    icon: {
      alignSelf: 'center',
      marginBottom: 12,
    },
    header: {
      fontSize: 16,
      fontFamily: 'Nunito-Bold',
      color: Colors.primaryColor,
      textAlign: 'center',
      marginBottom: 16,
    },
    content: {
      marginBottom: 8,
    },
    text: {
      fontSize: 13,
      fontFamily: 'Nunito-Regular',
      color: Colors.textColor,
      lineHeight: 20,
      marginBottom: 12,
    },
    listContainer: {
      marginBottom: 16,
    },
    listItem: {
      flexDirection: 'row',
      alignItems: 'flex-start',
      marginBottom: 8,
    },
    bulletPoint: {
      width: 4,
      height: 4,
      borderRadius: 2,
      backgroundColor: Colors.primaryColor,
      marginTop: 8,
      marginRight: 8,
    },
    listText: {
      fontSize: 12,
      fontFamily: 'Nunito-Regular',
      color: Colors.textColor,
      flex: 1,
      lineHeight: 18,
    },
    footerText: {
      fontSize: 11,
      fontFamily: 'Nunito-Italic',
      color: Colors.greyColor600,
      textAlign: 'center',
      marginTop: 8,
    },
    buttonContainer: {
      flexDirection: 'row',
      gap: 8,
      marginTop: 8,
      flexGrow: 1,
    },
    button: {
      flex: 1,
      borderRadius: 8,
      paddingVertical: 10,
      alignItems: 'center',
      justifyContent: 'center',
    },
    primaryButton: {
      backgroundColor: Colors.primaryColor,
    },
    secondaryButton: {
      backgroundColor: Colors.greyColor100,
      borderWidth: 1,
      borderColor: Colors.greyColor300,
    },
    buttonText: {
      fontSize: 13,
      fontFamily: 'Nunito-SemiBold',
    },
    primaryButtonText: {
      color: Colors.white,
    },
    secondaryButtonText: {
      color: Colors.textColor,
    },
  });

export default MiniDisclaimer;
